#!/usr/bin/env node

import { createHash } from 'node:crypto';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export const repoRoot = resolve(dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
export const defaultSchemaPath = join(
  repoRoot,
  'src',
  'search',
  'evaluation',
  'built-search-adapter-contract.json',
);
export const defaultRuntimePath = join(repoRoot, 'shared', 'built-search-adapter-contract.mjs');
export const defaultDeclarationPath = join(repoRoot, 'shared', 'built-search-adapter-contract.d.mts');

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function propertyName(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function refName(ref) {
  const prefix = '#/$defs/';
  if (typeof ref !== 'string' || !ref.startsWith(prefix)) {
    throw new Error(`Unsupported JSON Schema reference: ${String(ref)}`);
  }
  return ref.slice(prefix.length);
}

function renderType(schema) {
  if (schema['x-typescript-type']) return schema['x-typescript-type'];
  if (schema.$ref) return refName(schema.$ref);
  if (Object.hasOwn(schema, 'const')) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(' | ');
  if (schema.anyOf) return schema.anyOf.map(renderType).join(' | ');
  if (schema.oneOf) return schema.oneOf.map(renderType).join(' | ');
  if (Array.isArray(schema.type)) {
    return schema.type.map(type => renderType({ ...schema, type })).join(' | ');
  }
  switch (schema.type) {
    case 'null':
      return 'null';
    case 'boolean':
      return 'boolean';
    case 'integer':
    case 'number':
      return 'number';
    case 'string':
      return 'string';
    case 'array': {
      const item = renderType(schema.items ?? {});
      if (schema.minItems === schema.maxItems && Number.isInteger(schema.minItems)) {
        if (schema.minItems === 5) return `[${Array.from({ length: 5 }, () => item).join(', ')}]`;
        return `FixedLengthArray<${item}, ${schema.minItems}>`;
      }
      return `Array<${item}>`;
    }
    case 'object': {
      const properties = schema.properties ?? {};
      const required = new Set(schema.required ?? []);
      const fields = Object.entries(properties).map(([name, value]) => (
        `${propertyName(name)}${required.has(name) ? '' : '?'}: ${renderType(value)};`
      ));
      if (schema.additionalProperties && schema.additionalProperties !== false) {
        const value = renderType(schema.additionalProperties);
        if (fields.length === 0) return `Record<string, ${value}>`;
        fields.push(`[key: string]: ${value};`);
      }
      return `{ ${fields.join(' ')} }`;
    }
    default:
      return 'unknown';
  }
}

function searchMeasurementLanes(schema) {
  const lanes = schema.$defs?.SearchMeasurementLane?.enum;
  if (!Array.isArray(lanes)
      || lanes.length === 0
      || lanes.some(lane => typeof lane !== 'string')
      || new Set(lanes).size !== lanes.length) {
    throw new Error('SearchMeasurementLane must define a non-empty unique string enum');
  }
  return lanes;
}

function renderDeclarations(schema, schemaSha256) {
  const definitions = schema.$defs ?? {};
  const declarations = Object.entries(definitions)
    .map(([name, value]) => `export type ${name} = ${renderType(value)};`)
    .join('\n\n');
  const measurementLanes = searchMeasurementLanes(schema);
  return `// Generated by scripts/generate-built-search-adapter-contract.mjs. Do not edit.
/// <reference types="node" />

export const SCHEMA_SHA256: ${JSON.stringify(schemaSha256)};
export const SEARCH_MEASUREMENT_LANES: readonly [${measurementLanes
    .map(lane => JSON.stringify(lane)).join(', ')}];
export type FixedLengthArray<T, N extends number> = T[] & { length: N };

${declarations}

export function parseBuiltSearchAdapterExpected(value: unknown): BuiltSearchAdapterExpected;
export function parseBuiltSearchAdapterReport(
  value: unknown,
  expected: BuiltSearchAdapterExpected,
): BuiltSearchAdapterReport;
export function makeBuiltSearchAdapterFixture(
  input: BuiltSearchAdapterFixtureInput,
): BuiltSearchAdapterReport;
`;
}

function renderRuntime(schemaText, schemaSha256, schema) {
  const measurementLanes = searchMeasurementLanes(schema);
  return `// Generated by scripts/generate-built-search-adapter-contract.mjs. Do not edit.
import { isAbsolute } from 'node:path';

export const SCHEMA_SHA256 = ${JSON.stringify(schemaSha256)};
export const SEARCH_MEASUREMENT_LANES = Object.freeze(${JSON.stringify(measurementLanes)});
export const SCHEMA = JSON.parse(${JSON.stringify(schemaText)});

const PROVIDER_FUNCTIONS = Object.freeze({
  wiki: 'WikiIndexer.searchWithMeta',
  kg: 'MaestroGraph.searchUnified',
  code: 'runCodeSearch/MaestroGraph.searchCode',
  mixed: 'runMixedSearch',
  linked: 'runCodeSearch/MaestroGraph.openReadOnly.searchCode',
});

function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.keys(value).sort().map(key => [key, canonical(value[key])]),
  );
}

function sameJson(left, right) {
  return JSON.stringify(canonical(left)) === JSON.stringify(canonical(right));
}

function resolveRef(root, ref) {
  const prefix = '#/$defs/';
  if (typeof ref !== 'string' || !ref.startsWith(prefix)) {
    throw new TypeError(\`unsupported schema reference: \${String(ref)}\`);
  }
  const definition = root.$defs?.[ref.slice(prefix.length)];
  if (!definition) throw new TypeError(\`missing schema definition: \${ref}\`);
  return definition;
}

function validateSchema(value, schema, root, path, errors) {
  if (schema.$ref) {
    validateSchema(value, resolveRef(root, schema.$ref), root, path, errors);
    return;
  }
  if (schema.anyOf || schema.oneOf) {
    const choices = schema.anyOf ?? schema.oneOf;
    const valid = choices.some(choice => {
      const branchErrors = [];
      validateSchema(value, choice, root, path, branchErrors);
      return branchErrors.length === 0;
    });
    if (!valid) errors.push(\`\${path}: does not match any allowed schema\`);
    return;
  }
  if (Object.hasOwn(schema, 'const') && !Object.is(value, schema.const)) {
    errors.push(\`\${path}: expected constant \${JSON.stringify(schema.const)}\`);
    return;
  }
  if (schema.enum && !schema.enum.some(item => Object.is(item, value))) {
    errors.push(\`\${path}: expected one of \${schema.enum.map(String).join(', ')}\`);
    return;
  }
  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
  if (types.length > 0) {
    const matches = types.some(type => {
      if (type === 'null') return value === null;
      if (type === 'array') return Array.isArray(value);
      if (type === 'object') return typeof value === 'object' && value !== null && !Array.isArray(value);
      if (type === 'integer') return Number.isInteger(value);
      if (type === 'number') return typeof value === 'number' && Number.isFinite(value);
      return typeof value === type;
    });
    if (!matches) {
      errors.push(\`\${path}: expected type \${types.join(' | ')}\`);
      return;
    }
  }
  if (typeof value === 'string') {
    if (schema.minLength !== undefined && value.length < schema.minLength) {
      errors.push(\`\${path}: string is shorter than \${schema.minLength}\`);
    }
    if (schema.pattern && !(new RegExp(schema.pattern)).test(value)) {
      errors.push(\`\${path}: string does not match \${schema.pattern}\`);
    }
    if (schema.format === 'absolute-path' && !isAbsolute(value)) {
      errors.push(\`\${path}: expected an absolute path\`);
    }
  }
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) errors.push(\`\${path}: number must be finite\`);
    if (schema.minimum !== undefined && value < schema.minimum) {
      errors.push(\`\${path}: number is below \${schema.minimum}\`);
    }
    if (schema.maximum !== undefined && value > schema.maximum) {
      errors.push(\`\${path}: number is above \${schema.maximum}\`);
    }
  }
  if (Array.isArray(value)) {
    if (schema.minItems !== undefined && value.length < schema.minItems) {
      errors.push(\`\${path}: array has fewer than \${schema.minItems} items\`);
    }
    if (schema.maxItems !== undefined && value.length > schema.maxItems) {
      errors.push(\`\${path}: array has more than \${schema.maxItems} items\`);
    }
    if (schema.items) {
      value.forEach((item, index) => validateSchema(item, schema.items, root, \`\${path}[\${index}]\`, errors));
    }
  }
  if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
    const properties = schema.properties ?? {};
    for (const name of schema.required ?? []) {
      if (!Object.hasOwn(value, name)) errors.push(\`\${path}.\${name}: required property is missing\`);
    }
    for (const [name, nested] of Object.entries(properties)) {
      if (Object.hasOwn(value, name)) validateSchema(value[name], nested, root, \`\${path}.\${name}\`, errors);
    }
    for (const name of Object.keys(value)) {
      if (Object.hasOwn(properties, name)) continue;
      if (schema.additionalProperties === false) {
        errors.push(\`\${path}.\${name}: additional property is forbidden\`);
      } else if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
        validateSchema(value[name], schema.additionalProperties, root, \`\${path}.\${name}\`, errors);
      }
    }
  }
}

function parseDefinition(value, name) {
  const definition = SCHEMA.$defs?.[name];
  if (!definition) throw new TypeError(\`unknown schema definition: \${name}\`);
  const errors = [];
  validateSchema(value, definition, SCHEMA, '$', errors);
  if (errors.length > 0) {
    throw new TypeError(\`\${name} validation failed:\\n\${errors.map(error => \`- \${error}\`).join('\\n')}\`);
  }
  return value;
}

export function parseBuiltSearchAdapterExpected(value) {
  const expected = parseDefinition(value, 'BuiltSearchAdapterExpected');
  const ids = expected.queries.map(query => query.queryId);
  if (new Set(ids).size !== ids.length) {
    throw new TypeError('BuiltSearchAdapterExpected queryId values must be unique');
  }
  for (const query of expected.queries) {
    if (PROVIDER_FUNCTIONS[query.provider] !== query.function) {
      throw new TypeError(\`provider/function mismatch for query: \${query.queryId}\`);
    }
  }
  return expected;
}

function assertReportSemantics(report, expected) {
  if (report.qrelsSha256 !== expected.qrelsSha256) {
    throw new TypeError('report qrelsSha256 does not match expected');
  }
  if (report.workspace.root !== expected.workspaceRoot
      || report.workspace.cwd !== expected.workspaceRoot
      || report.workspace.maestroProjectRoot !== expected.workspaceRoot) {
    throw new TypeError('report workspace roots do not match expected');
  }
  for (const [name, value] of Object.entries(expected.databasePaths)) {
    if (report.workspace[name] !== value) {
      throw new TypeError(\`report workspace path does not match expected: \${name}\`);
    }
  }
  if (!sameJson(report.runner, expected.runner)) {
    throw new TypeError('report runner does not match expected');
  }
  if (expected.corpus !== undefined
      && !sameJson(report.corpus, expected.corpus)) {
    throw new TypeError('report corpus evidence does not match expected');
  }
  if (report.evidence.queries.length !== expected.queries.length) {
    throw new TypeError('report query evidence count does not match expected');
  }
  for (let queryIndex = 0; queryIndex < expected.queries.length; queryIndex += 1) {
    const expectedQuery = expected.queries[queryIndex];
    const actual = report.evidence.queries[queryIndex];
    for (const name of ['queryId', 'category', 'provider', 'function', 'expectedCount']) {
      if (actual[name] !== expectedQuery[name]) {
        throw new TypeError(\`query evidence order or metadata mismatch at \${queryIndex}/\${name}\`);
      }
    }
    let stableIds = null;
    for (let runIndex = 0; runIndex < actual.runs.length; runIndex += 1) {
      const results = actual.runs[runIndex].results;
      if (results.length !== expectedQuery.expectedCount) {
        throw new TypeError(
          \`query \${actual.queryId} run \${runIndex + 1} result count is not exact \`
          + \`(expected \${expectedQuery.expectedCount}, actual \${results.length})\`,
        );
      }
      const ids = results.map(result => result.id);
      if (new Set(ids).size !== ids.length) {
        throw new TypeError(\`query \${actual.queryId} run \${runIndex + 1} has duplicate result IDs\`);
      }
      for (let resultIndex = 0; resultIndex < results.length; resultIndex += 1) {
        if (results[resultIndex].rank !== resultIndex + 1) {
          throw new TypeError(\`query \${actual.queryId} run \${runIndex + 1} ranks are not exact\`);
        }
      }
      if (stableIds === null) stableIds = ids;
      else if (!sameJson(ids, stableIds)) {
        throw new TypeError(\`query \${actual.queryId} result order is unstable\`);
      }
    }
  }
  for (let index = 0; index < report.evidence.events.length; index += 1) {
    if (report.evidence.events[index].sequence !== index + 1) {
      throw new TypeError('evidence event sequence is not exact');
    }
  }
  if (!sameJson(report.protectedState.before, report.protectedState.after)) {
    throw new TypeError('protected state before/after evidence differs');
  }
}

export function parseBuiltSearchAdapterReport(value, expectedValue) {
  const expected = parseBuiltSearchAdapterExpected(expectedValue);
  const report = parseDefinition(value, 'BuiltSearchAdapterReport');
  assertReportSemantics(report, expected);
  return report;
}

function percentile(samples, fraction) {
  const sorted = [...samples].sort((left, right) => left - right);
  return sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * fraction))];
}

function countEvent(events, event) {
  return events.filter(row => row.event === event).length;
}

function zeroMetrics() {
  return { ndcgAt10: 0, mrrAt10: 0, recallAt20: 0 };
}

export function makeBuiltSearchAdapterFixture(inputValue) {
  const input = parseDefinition(inputValue, 'BuiltSearchAdapterFixtureInput');
  const expected = parseBuiltSearchAdapterExpected(input.expected);
  const categories = Object.fromEntries(
    [...new Set(expected.queries.map(query => query.category))].sort()
      .map(category => [category, zeroMetrics()]),
  );
  const events = input.events;
  const reported = {
    metrics: { overall: zeroMetrics(), categories },
    overallNdcgGain: 0,
    maxCategoryNdcgDrop: 0,
    stability: { runs: 5, topK: 20, stableTop20: true },
    latency: {
      kgWarmP95Ms: percentile(input.kgWarmSamplesMs, 0.95),
      kgWarmMaxMs: Math.max(...input.kgWarmSamplesMs),
      wikiQueryP95Ms: percentile(input.wikiQuerySamplesMs, 0.95),
      wikiIndexP95Ms: percentile(input.wikiIndexSamples.map(sample => sample.durationMs), 0.95),
    },
    integrity: {
      deprecatedLeakCount: 0,
      unauthorizedWorkspaceHitCount: 0,
      provenanceLossCount: 0,
      attachOrMergeCalls: countEvent(events, 'database-attach-or-merge'),
    },
    sideEffects: {
      daemonLookupCalls: countEvent(events, 'daemon-lookup'),
      daemonStartCalls: countEvent(events, 'daemon-start'),
      filesystemCacheReadCalls: countEvent(events, 'filesystem-cache-read'),
      filesystemCacheWriteCalls: countEvent(events, 'filesystem-cache-write'),
      filesystemIndexWriteCalls: countEvent(events, 'filesystem-index-write'),
      embeddingBuildCalls: countEvent(events, 'embedding-build'),
      embeddingSaveCalls: countEvent(events, 'embedding-save'),
      credibilityHitWriteCalls: countEvent(events, 'credibility-hit-write'),
    },
    ...(input.reportedOverrides ?? {}),
  };
  const report = {
    schema_version: 'built-search-adapter/1.1',
    ok: true,
    qrelsSha256: expected.qrelsSha256,
    ...(expected.corpus === undefined ? {} : { corpus: expected.corpus }),
    evidence: {
      queries: expected.queries.map(query => ({
        ...query,
        runs: input.queryRuns[query.queryId],
      })),
      events,
      latency: {
        kgWarmSamplesMs: input.kgWarmSamplesMs,
        wikiQuerySamplesMs: input.wikiQuerySamplesMs,
        wikiIndexWarmupSamples: input.wikiIndexWarmupSamples,
        wikiIndexSamples: input.wikiIndexSamples,
      },
    },
    reported,
    workspace: {
      root: expected.workspaceRoot,
      cwd: expected.workspaceRoot,
      maestroProjectRoot: expected.workspaceRoot,
      ...expected.databasePaths,
      persistence: 'memory-only',
      executionMode: 'read-only-probe',
    },
    protectedState: input.protectedState,
    runner: expected.runner,
  };
  return parseBuiltSearchAdapterReport(report, expected);
}
`;
}

export function generateContractArtifacts(schemaBytes) {
  const schemaText = schemaBytes.toString('utf8');
  const schema = JSON.parse(schemaText);
  if (schema.$ref !== '#/$defs/BuiltSearchAdapterReport'
      || !schema.$defs?.BuiltSearchAdapterExpected
      || !schema.$defs?.BuiltSearchAdapterFixtureInput) {
    throw new Error('Adapter contract schema is missing required definitions');
  }
  const schemaSha256 = sha256(schemaBytes);
  return {
    schemaSha256,
    runtime: renderRuntime(schemaText, schemaSha256, schema),
    declaration: renderDeclarations(schema, schemaSha256),
  };
}

