async function verifySemanticBehavior(runtimePath, expectedSha256) {
  const module = await import(`${pathToFileURL(runtimePath).href}?contract-check=${Date.now()}`);
  if (module.SCHEMA_SHA256 !== expectedSha256) {
    throw new Error('Generated runtime SCHEMA_SHA256 does not match schema bytes');
  }
  const input = fixtureInput(module);
  const report = module.makeBuiltSearchAdapterFixture(input);
  module.parseBuiltSearchAdapterReport(report, input.expected);
  const faults = [
    { ...report, extra: true },
    {
      ...report,
      evidence: {
        ...report.evidence,
        queries: [{
          ...report.evidence.queries[0],
          runs: [
            { results: [] },
            ...report.evidence.queries[0].runs.slice(1),
          ],
        }],
      },
    },
    {
      ...report,
      evidence: {
        ...report.evidence,
        latency: {
          ...report.evidence.latency,
          wikiIndexWarmupSamples: report.evidence.latency.wikiIndexWarmupSamples.slice(1),
        },
      },
    },
  ];
  for (const fault of faults) {
    let rejected = false;
    try {
      module.parseBuiltSearchAdapterReport(fault, input.expected);
    } catch {
      rejected = true;
    }
    if (!rejected) throw new Error('Generated runtime semantic drift probe accepted invalid evidence');
  }
}

export async function checkGeneratedArtifacts({
  schemaPath = defaultSchemaPath,
  runtimePath = defaultRuntimePath,
  declarationPath = defaultDeclarationPath,
} = {}) {
  const schemaBytes = readFileSync(schemaPath);
  const generated = generateContractArtifacts(schemaBytes);
  const drift = [];
  if (!existsSync(runtimePath)
      || readFileSync(runtimePath, 'utf8') !== generated.runtime) {
    drift.push(runtimePath);
  }
  if (!existsSync(declarationPath)
      || readFileSync(declarationPath, 'utf8') !== generated.declaration) {
    drift.push(declarationPath);
  }
  if (drift.length > 0) {
    throw new Error(
      `Built search adapter contract artifacts are stale:\n${drift.map(path => `- ${path}`).join('\n')}`,
    );
  }
  await verifySemanticBehavior(runtimePath, generated.schemaSha256);
  return generated;
}

function parsePathArguments(argv) {
  const values = new Map();
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index];
    if (value === '--check') continue;
    const next = argv[index + 1];
    if (!['--schema', '--runtime', '--declaration'].includes(value) || !next) {
      throw new Error(`Unknown or incomplete generator argument: ${value}`);
    }
    values.set(value, isAbsolute(next) ? next : resolve(repoRoot, next));
    index += 1;
  }
  return {
    schemaPath: values.get('--schema') ?? defaultSchemaPath,
    runtimePath: values.get('--runtime') ?? defaultRuntimePath,
    declarationPath: values.get('--declaration') ?? defaultDeclarationPath,
  };
}

async function main() {
  const paths = parsePathArguments(process.argv.slice(2));
  if (process.argv.includes('--check')) {
    const generated = await checkGeneratedArtifacts(paths);
    process.stdout.write(`built search adapter contract ${generated.schemaSha256}: schema, bytes, and semantics OK\n`);
    return;
  }
  const generated = generateContractArtifacts(readFileSync(paths.schemaPath));
  mkdirSync(dirname(paths.runtimePath), { recursive: true });
  writeFileSync(paths.runtimePath, generated.runtime, 'utf8');
  writeFileSync(paths.declarationPath, generated.declaration, 'utf8');
  await verifySemanticBehavior(paths.runtimePath, generated.schemaSha256);
  process.stdout.write(`generated built search adapter contract ${generated.schemaSha256}\n`);
}

if (resolve(process.argv[1] ?? '') === resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))) {
  main().catch(error => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}
