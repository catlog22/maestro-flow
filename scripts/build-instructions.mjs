#!/usr/bin/env node
// ---------------------------------------------------------------------------
// build-instructions.mjs
//
// Generates the per-host always-on instruction files from a shared kernel:
//   workflows/<platform>-instructions.md  ←  workflows/instructions-kernel.md
//                                         +  workflows/instructions-delta-<platform>.md (optional)
//
// The tag-injector installs these files verbatim, so the kernel is composed
// here at build time instead of being duplicated across four hand-maintained
// copies. Edit the kernel/delta sources, never the generated outputs.
//
//   node scripts/build-instructions.mjs          regenerate outputs
//   node scripts/build-instructions.mjs --check  verify outputs match sources
//                                                and the kernel fits its budget
//
// --check fails (exit 1) when a generated file drifts from its sources or the
// kernel exceeds KERNEL_LINE_BUDGET lines — the always-on budget is enforced
// here because nothing else sees these files before install.
// ---------------------------------------------------------------------------

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = dirname(__dirname);
const WORKFLOWS = join(REPO_ROOT, 'workflows');

/** Platforms with a generated instructions file; delta is optional. */
const PLATFORMS = [
  { id: 'claude', delta: true },
  { id: 'grok', delta: true },
  { id: 'codex', delta: true },
  { id: 'agy', delta: false },
];

/** Always-on budget: kernel above this many lines fails --check. */
const KERNEL_LINE_BUDGET = 200;

const GENERATED_MARKER =
  '<!-- generated by scripts/build-instructions.mjs — edit workflows/instructions-kernel.md and workflows/instructions-delta-*.md instead -->';

function compose(platform) {
  const kernelPath = join(WORKFLOWS, 'instructions-kernel.md');
  const kernel = readFileSync(kernelPath, 'utf8').trimEnd();
  let delta = '';
  if (platform.delta) {
    const deltaPath = join(WORKFLOWS, `instructions-delta-${platform.id}.md`);
    if (!existsSync(deltaPath)) {
      throw new Error(`missing delta source: workflows/instructions-delta-${platform.id}.md`);
    }
    delta = readFileSync(deltaPath, 'utf8').trim();
  }
  const body = delta ? `${kernel}\n\n${delta}` : kernel;
  // Keep `<!-- session-mode: ... -->` as the very first line — the session-run
  // prompt lint anchors on it — with the generated marker right after.
  const lines = body.split('\n');
  if (/^<!-- session-mode: [^ ]+ -->/.test(lines[0])) {
    return `${lines[0]}\n${GENERATED_MARKER}\n${lines.slice(1).join('\n')}\n`;
  }
  return `${GENERATED_MARKER}\n${body}\n`;
}

function lineCount(text) {
  return text.split('\n').length;
}

function main() {
  const check = process.argv.includes('--check');
  const kernelLines = lineCount(readFileSync(join(WORKFLOWS, 'instructions-kernel.md'), 'utf8').trimEnd());
  let failed = false;

  // Measurement table — printed in both modes so CI logs the current budget.
  const rows = [];
  for (const platform of PLATFORMS) {
    const outputPath = join(WORKFLOWS, `${platform.id}-instructions.md`);
    const expected = compose(platform);
    if (check) {
      const actual = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : null;
      if (actual !== expected) {
        console.error(`DRIFT: workflows/${platform.id}-instructions.md — run scripts/build-instructions.mjs`);
        failed = true;
      }
    } else {
      writeFileSync(outputPath, expected);
    }
    rows.push([`${platform.id}-instructions.md`, lineCount(expected)]);
  }
  const chinesePath = join(WORKFLOWS, 'chinese-response.md');
  if (existsSync(chinesePath)) {
    rows.push(['chinese-response.md (optional inject)', lineCount(readFileSync(chinesePath, 'utf8').trimEnd())]);
  }

  console.log(`kernel: ${kernelLines} lines (budget ${KERNEL_LINE_BUDGET})`);
  for (const [name, lines] of rows) console.log(`  ${name}: ${lines}`);

  if (kernelLines > KERNEL_LINE_BUDGET) {
    console.error(`BUDGET: kernel is ${kernelLines} lines, over the ${KERNEL_LINE_BUDGET}-line always-on budget`);
    failed = true;
  }

  if (failed) process.exit(1);
  console.log(check ? 'instructions: in sync' : 'instructions: generated');
}

main();
